-- Description: Core tables for users, roles, categories, blogs, comments, tags
-- Compatible with PostgreSQL 16+ and H2 Database
-- ==============================================================================

-- 1. ROLES TABLE
CREATE TABLE IF NOT EXISTS roles (
    role_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_name VARCHAR(50) NOT NULL UNIQUE,
    created_by VARCHAR(255),
    created_date TIMESTAMP,
    last_user_by VARCHAR(255),
    last_user_date TIMESTAMP
);

-- 2. USERS TABLE
CREATE TABLE IF NOT EXISTS users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(100) NOT NULL UNIQUE,
    email VARCHAR(150) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    first_name VARCHAR(100),
    last_name VARCHAR(100),
    is_account_non_expired BOOLEAN NOT NULL DEFAULT TRUE,
    is_account_non_locked BOOLEAN NOT NULL DEFAULT TRUE,
    is_credentials_non_expired BOOLEAN NOT NULL DEFAULT TRUE,
    is_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_by VARCHAR(255),
    created_date TIMESTAMP,
    last_user_by VARCHAR(255),
    last_user_date TIMESTAMP
);

-- 3. USER_ROLES (MANY-TO-MANY)
CREATE TABLE IF NOT EXISTS user_roles (
    user_id BIGINT NOT NULL,
    role_id BIGINT NOT NULL,
    PRIMARY KEY (user_id, role_id),
    CONSTRAINT fk_user_roles_user FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_user_roles_role FOREIGN KEY (role_id) REFERENCES roles (role_id) ON DELETE CASCADE
);

-- 4. BLOG_CATEGORIES TABLE
CREATE TABLE IF NOT EXISTS blog_categories (
    blog_category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(250) NOT NULL UNIQUE,
    created_by VARCHAR(255),
    created_date TIMESTAMP,
    last_user_by VARCHAR(255),
    last_user_date TIMESTAMP
);

-- 5. BLOGS TABLE
CREATE TABLE IF NOT EXISTS blogs (
    blog_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    header VARCHAR(255) NOT NULL UNIQUE,
    title VARCHAR(255),
    content TEXT,
    image VARCHAR(255),
    blog_category_id BIGINT NOT NULL,
    author_user_id BIGINT,
    created_by VARCHAR(255),
    created_date TIMESTAMP,
    last_user_by VARCHAR(255),
    last_user_date TIMESTAMP,
    CONSTRAINT fk_blogs_category FOREIGN KEY (blog_category_id) REFERENCES blog_categories (blog_category_id),
    CONSTRAINT fk_blogs_author FOREIGN KEY (author_user_id) REFERENCES users (user_id)
);

-- 6. COMMENTS TABLE
CREATE TABLE IF NOT EXISTS comments (
    comment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content VARCHAR(1000) NOT NULL,
    is_approved BOOLEAN NOT NULL DEFAULT TRUE,
    blog_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    created_by VARCHAR(255),
    created_date TIMESTAMP,
    last_user_by VARCHAR(255),
    last_user_date TIMESTAMP,
    CONSTRAINT fk_comments_blog FOREIGN KEY (blog_id) REFERENCES blogs (blog_id) ON DELETE CASCADE,
    CONSTRAINT fk_comments_user FOREIGN KEY (user_id) REFERENCES users (user_id) ON DELETE CASCADE
);

-- 7. TAGS TABLE
CREATE TABLE IF NOT EXISTS tags (
    tag_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE,
    created_by VARCHAR(255),
    created_date TIMESTAMP,
    last_user_by VARCHAR(255),
    last_user_date TIMESTAMP
);

-- 8. BLOG_TAGS (MANY-TO-MANY)
CREATE TABLE IF NOT EXISTS blog_tags (
    blog_id BIGINT NOT NULL,
    tag_id BIGINT NOT NULL,
    PRIMARY KEY (blog_id, tag_id),
    CONSTRAINT fk_blog_tags_blog FOREIGN KEY (blog_id) REFERENCES blogs (blog_id) ON DELETE CASCADE,
    CONSTRAINT fk_blog_tags_tag FOREIGN KEY (tag_id) REFERENCES tags (tag_id) ON DELETE CASCADE
);

