export function haversineDistanceKm(coord1: [number, number], coord2: [number, number]): number {
  const R = 6371; // Earth radius in km
  const dLat = ((coord2[0] - coord1[0]) * Math.PI) / 180;
  const dLng = ((coord2[1] - coord1[1]) * Math.PI) / 180;
  const a =
    Math.sin(dLat / 2) * Math.sin(dLat / 2) +
    Math.cos((coord1[0] * Math.PI) / 180) *
      Math.cos((coord2[0] * Math.PI) / 180) *
      Math.sin(dLng / 2) *
      Math.sin(dLng / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return R * c;
}

export interface DispatchSlaResult {
  hub: CraftHub;
  distanceKm: number;
  roadDistanceKm: number;
  estimatedMinutes: number;
  routePoints: [number, number][];
}

export function generateCurvedArcPoints(
  start: [number, number],
  end: [number, number],
  numPoints: number = 20
): [number, number][] {
  const points: [number, number][] = [];
  const midLat = (start[0] + end[0]) / 2;
  const midLng = (start[1] + end[1]) / 2;
  // Perpendicular curve offset for aesthetic arc
  const dx = end[1] - start[1];
  const dy = end[0] - start[0];
  const offset = 0.12;
  const ctrlLat = midLat - dx * offset;
  const ctrlLng = midLng + dy * offset;

  for (let i = 0; i <= numPoints; i++) {
    const t = i / numPoints;
    const lat = (1 - t) * (1 - t) * start[0] + 2 * (1 - t) * t * ctrlLat + t * t * end[0];
    const lng = (1 - t) * (1 - t) * start[1] + 2 * (1 - t) * t * ctrlLng + t * t * end[1];
    points.push([lat, lng]);
  }
  return points;
}

export function calculateDispatchSla(
  targetLatLng: [number, number],
  categoryIcon?: string
): DispatchSlaResult {
  // Match category with specialized craft hub first
  let eligibleHubs = ankaraCraftHubs;
  if (categoryIcon && categoryIcon !== 'all') {
    const matched = ankaraCraftHubs.filter(h =>
      (h.primaryCategories as string[]).includes(categoryIcon)
    );
    if (matched.length > 0) {
      eligibleHubs = matched;
    }
  }

  // Find closest hub
  let nearestHub = eligibleHubs[0];
  let minDistance = Number.MAX_VALUE;

  for (const hub of eligibleHubs) {
    const dist = haversineDistanceKm(hub.latLng, targetLatLng);
    if (dist < minDistance) {
      minDistance = dist;
      nearestHub = hub;
    }
  }

  const ROAD_CIRCUITY_FACTOR = 1.32; // Ankara urban road circuity
  const AVERAGE_SPEED_KMH = 38; // Average urban traffic speed
  const BASE_DISPATCH_MINUTES = 8; // Preparation buffer

  const roadDistanceKm = minDistance * ROAD_CIRCUITY_FACTOR;
  const transitMinutes = (roadDistanceKm / AVERAGE_SPEED_KMH) * 60;
  const estimatedMinutes = Math.max(15, Math.round(BASE_DISPATCH_MINUTES + transitMinutes));

  const routePoints = generateCurvedArcPoints(nearestHub.latLng, targetLatLng);

  return {
    hub: nearestHub,
    distanceKm: minDistance,
    roadDistanceKm,
    estimatedMinutes,
    routePoints,
  };
}


