export interface GeoCluster<T> {
  id: string;
  isCluster: boolean;
  center: [number, number];
  count: number;
  district: string;
  label: string;
  categoryIcon?: string;
  items: T[];
}

export function clusterShops(shops: ShopPin[], zoom: number): GeoCluster<ShopPin>[] {
  if (zoom >= 13 || shops.length <= 1) {
    return shops.map(shop => {
      const lat = shop.latLng?.lat ?? shop.coords.y;
      const lng = shop.latLng?.lng ?? shop.coords.x;
      return {
        id: shop.id,
        isCluster: false,
        center: [lat, lng],
        count: 1,
        district: shop.district,
        label: shop.name,
        categoryIcon: shop.categoryIcon,
        items: [shop],
      };
    });
  }

  // Dynamic cluster distance threshold based on map zoom
  let thresholdKm = 3.6;
  if (zoom <= 10) thresholdKm = 7.5;
  else if (zoom === 11) thresholdKm = 4.5;
  else if (zoom === 12) thresholdKm = 2.4;

  const clusters: GeoCluster<ShopPin>[] = [];
  const assigned = new Set<string>();

  for (let i = 0; i < shops.length; i++) {
    const shop = shops[i];
    if (assigned.has(shop.id)) continue;

    const lat1 = shop.latLng?.lat ?? shop.coords.y;
    const lng1 = shop.latLng?.lng ?? shop.coords.x;
    const clusterItems: ShopPin[] = [shop];
    assigned.add(shop.id);

    for (let j = i + 1; j < shops.length; j++) {
      const candidate = shops[j];
      if (assigned.has(candidate.id)) continue;

      const lat2 = candidate.latLng?.lat ?? candidate.coords.y;
      const lng2 = candidate.latLng?.lng ?? candidate.coords.x;
      const dist = haversineDistanceKm([lat1, lng1], [lat2, lng2]);

      if (dist <= thresholdKm) {
        clusterItems.push(candidate);
        assigned.add(candidate.id);
      }
    }

    if (clusterItems.length === 1) {
      clusters.push({
        id: shop.id,
        isCluster: false,
        center: [lat1, lng1],
        count: 1,
        district: shop.district,
        label: shop.name,
        categoryIcon: shop.categoryIcon,
        items: [shop],
      });
    } else {
      // Centroid
      const totalLat = clusterItems.reduce((sum, s) => sum + (s.latLng?.lat ?? s.coords.y), 0);
      const totalLng = clusterItems.reduce((sum, s) => sum + (s.latLng?.lng ?? s.coords.x), 0);
      const centerLat = Number((totalLat / clusterItems.length).toFixed(4));
      const centerLng = Number((totalLng / clusterItems.length).toFixed(4));

      // District frequency
      const districtCounts: Record<string, number> = {};
      clusterItems.forEach(s => {
        districtCounts[s.district] = (districtCounts[s.district] || 0) + 1;
      });
      let predominantDistrict = shop.district;
      let maxDCount = 0;
      for (const [dist, cnt] of Object.entries(districtCounts)) {
        if (cnt > maxDCount) {
          maxDCount = cnt;
          predominantDistrict = dist;
        }
      }

      clusters.push({
        id: `cluster-${shop.id}-${clusterItems.length}`,
        isCluster: true,
        center: [centerLat, centerLng],
        count: clusterItems.length,
        district: predominantDistrict,
        label: `${predominantDistrict} · ${clusterItems.length} Atölye`,
        categoryIcon: clusterItems[0].categoryIcon,
        items: clusterItems,
      });
    }
  }

  return clusters;
}


/**
 * Chaikin's Corner-Cutting Algorithm:
 * Mathematically subdivides polygon line segments using 1/4 and 3/4 cut ratios,
 * transforming coarse polygonal boundaries into smooth, continuous organic curves
 * adhering to Apple Maps & Airbnb cartographic standards.
 */
export function chaikinSmooth(
  points: [number, number][],
  iterations = 2,
  isClosed = true
): [number, number][] {
  if (!points || points.length < 3) return points;
  const isDuplicateEnd =
    points[0][0] === points[points.length - 1][0] &&
    points[0][1] === points[points.length - 1][1];
  let pts = isDuplicateEnd ? points.slice(0, -1) : [...points];

  for (let it = 0; it < iterations; it++) {
    const smoothed: [number, number][] = [];
    const n = pts.length;
    for (let i = 0; i < n; i++) {
      const p0 = pts[i];
      const p1 = pts[(i + 1) % n];
      smoothed.push([
        Number((0.75 * p0[0] + 0.25 * p1[0]).toFixed(6)),
        Number((0.75 * p0[1] + 0.25 * p1[1]).toFixed(6)),
      ]);
      smoothed.push([
        Number((0.25 * p0[0] + 0.75 * p1[0]).toFixed(6)),
        Number((0.25 * p0[1] + 0.75 * p1[1]).toFixed(6)),
      ]);
    }
    pts = smoothed;
  }
  if (isClosed) {
    pts.push([pts[0][0], pts[0][1]]);
  }
  return pts;
}
